"""Phase 4: exploratory data analysis. Figures -> outputs/figures, notes -> outputs/reports/eda_notes.md"""
import numpy as np
import pandas as pd

from common import *

df = pd.read_csv(INTEGRATED_CSV, parse_dates=["date"])
ser = df.set_index("date")["price_php_kg"]
raw = df.set_index("date")["price_php_kg_raw"]
valid = ser.dropna()
lp = np.log(valid)
ret = lp.diff().dropna()                               # monthly log return
notes = ["# EDA notes (auto-generated by 03_eda.py)\n"]

# ---------------------------------------------------------------- 1. price trend
fig, ax = new_fig(figsize=(9, 4.2))
style_ax(ax)
ax.plot(raw.index, raw.values, color=MUTED, linewidth=1, label="raw (placeholder year shown in grey)")
ax.plot(valid.index, valid.values, color=BLUE, linewidth=2, label="used as target")
for y in df.loc[df["flat_year_flag"], "year"].unique():
    ax.axvspan(pd.Timestamp(f"{y}-01-01"), pd.Timestamp(f"{y}-12-31"), color=RED, alpha=0.12, linewidth=0)
    ax.text(pd.Timestamp(f"{y}-01-01"), valid.max() * 0.15, f"{y}: 12 identical\nvalues, excluded", fontsize=8, color=RED, ha="right")
for d_, txt in [("1995-08-01", "1995"), ("2008-06-01", "2008"), ("2018-09-01", "2018")]:
    d_ = pd.Timestamp(d_)
    ax.annotate(txt, (d_, raw.loc[d_]), xytext=(0, 10), textcoords="offset points", ha="center", fontsize=8.5, color=INK2)
ax.axvline(TRAIN_END + pd.offsets.MonthEnd(0), color=AXIS, linestyle="--", linewidth=1)
ax.axvline(VAL_END + pd.offsets.MonthEnd(0), color=AXIS, linestyle="--", linewidth=1)
ymax = ax.get_ylim()[1]
for x0, x1, lab in [(valid.index.min(), TRAIN_END, "train"), (TRAIN_END, VAL_END, "validation"), (VAL_END, valid.index.max(), "test")]:
    ax.text(x0 + (x1 - x0) / 2, 9.5, lab, ha="center", va="bottom", fontsize=8.5, color=INK2)
ax.set_ylabel("PHP per kg", color=INK2)
title(ax, "Regular milled rice, national retail price (monthly)")
ax.legend(frameon=False, fontsize=8.5, loc="center left", labelcolor=INK2)
save_fig(fig, "eda1_price_trend.png")
mx = valid.idxmax()
notes.append(f"- **Trend.** Price rose from {valid.iloc[0]:.2f} PHP/kg ({valid.index[0]:%Y-%m}) to {valid.iloc[-1]:.2f} "
             f"({valid.index[-1]:%Y-%m}); peak {valid.max():.2f} in {mx:%Y-%m}. The series trends strongly upward, so models "
             "should predict changes (or log-ratios) rather than raw levels, and R² on price levels will look high for any model.")
notes.append("- **Classification.** The file has one classification and one location, so there is no per-classification "
             "comparison to plot.")

# ---------------------------------------------------------------- 2. annual inflation and demand
ann = df.groupby("year").agg(infl=("prev_year_inflation_pct", "first"), dem=("prev_year_demand_kmt", "first"),
                              dg=("prev_year_demand_growth_pct", "first"))
ann.index = ann.index - 1                                  # undo the +1 shift: values belong to year Y-1
fig, axes = new_fig(1, 2, figsize=(10, 3.6))
for ax in axes:
    style_ax(ax)
axes[0].plot(ann.index, ann["infl"], color=ORANGE, linewidth=2)
axes[0].set_ylabel("percent", color=INK2)
title(axes[0], "Inflation, headline, World Bank (annual)")
axes[1].plot(ann.index, ann["dem"], color=AQUA, linewidth=2)
axes[1].set_ylabel("thousand MT", color=INK2)
title(axes[1], "Rice demand: net food disposable (annual)")
save_fig(fig, "eda2_inflation_demand.png")
ann = ann.dropna(subset=["infl"])
imin = ann["infl"].idxmin()
notes.append(f"- **Inflation** was {ann['infl'].iloc[0]:.1f}% in {ann.index[0]}, reached its low of {ann['infl'].min():.1f}% in {imin} "
             f"and was {ann['infl'].iloc[-1]:.1f}% in {ann.index[-1]}; it is a noisy annual series with {ann['infl'].nunique()} distinct values.")
notes.append("- **Demand** (net food disposable) climbs steadily with population and income; its level trends like price, "
             "so only its growth rate is used as a predictor.")

# ---------------------------------------------------------------- 3. missing-data pattern
grid = df.pivot(index="year", columns="month", values="price_php_kg_raw").notna().astype(int)
flag = df.pivot(index="year", columns="month", values="flat_year_flag").astype(int)
code = grid.copy()
code[flag == 1] = 2                                         # 2 = observed but excluded as placeholder
fig, ax = new_fig(figsize=(6.5, 7))
from matplotlib.colors import ListedColormap
ax.imshow(code.values, aspect="auto", cmap=ListedColormap([RED, BLUE, "#e0a3a3"]), vmin=0, vmax=2)
ax.set_xticks(range(12)); ax.set_xticklabels(range(1, 13), fontsize=8)
ax.set_yticks(range(0, len(code), 4)); ax.set_yticklabels(code.index[::4], fontsize=8)
ax.set_xlabel("month", color=INK2)
title(ax, "Price observations: blue = used, pink = placeholder year (excluded), red = missing")
ax.title.set_fontsize(9)
save_fig(fig, "eda3_missing_data_pattern.png")
miss = int((code == 0).sum().sum())
n_inf = int(df["prev_year_inflation_pct"].isna().sum())
n_dg = int(df["prev_year_demand_growth_pct"].isna().sum())
notes.append(f"- **Missing data.** {miss} months are absent from the price file; "
             f"{int(df['flat_year_flag'].sum())} months are present but excluded as placeholders. Previous-year inflation is empty for "
             f"{n_inf} months (1990, no 1989 value) and previous-year demand growth for {n_dg} months (1990-1991), so models that use "
             "them can start only in 1992. All feature sets are compared on the same rows.")

# ---------------------------------------------------------------- 4. correlations (on changes, not levels)
cdf = pd.DataFrame({
    "monthly log return": ret,
    "return, prev month": ret.shift(1),
    "return, 12m avg": ret.rolling(12).mean().shift(1),
    "prev-year inflation": df.set_index("date")["prev_year_inflation_pct"].reindex(ret.index),
    "prev-year demand growth": df.set_index("date")["prev_year_demand_growth_pct"].reindex(ret.index),
}).dropna()
cm = cdf.corr()
fig, ax = new_fig(figsize=(6, 5))
im = ax.imshow(cm.values, cmap="RdBu_r", vmin=-1, vmax=1)
ax.set_xticks(range(len(cm))); ax.set_xticklabels(cm.columns, rotation=30, ha="right", fontsize=8)
ax.set_yticks(range(len(cm))); ax.set_yticklabels(cm.columns, fontsize=8)
for i in range(len(cm)):
    for j in range(len(cm)):
        ax.text(j, i, f"{cm.values[i, j]:.2f}", ha="center", va="center", fontsize=8,
                color="white" if abs(cm.values[i, j]) > 0.6 else INK)
title(ax, "Correlation of changes (not levels)")
save_fig(fig, "eda4_correlations.png")
lvl = pd.DataFrame({"price": valid, "demand": df.set_index("date")["prev_year_demand_kmt"].reindex(valid.index)}).dropna()
notes.append(f"- **Correlations.** Price level vs demand level has r = {lvl.corr().iloc[0, 1]:.2f}, but both just trend upward over time, "
             "so this is not evidence of a relationship (spurious correlation). On changes: "
             f"return vs previous-month return r = {cm.loc['monthly log return', 'return, prev month']:.2f}, "
             f"vs previous-year inflation r = {cm.loc['monthly log return', 'prev-year inflation']:.2f}, "
             f"vs previous-year demand growth r = {cm.loc['monthly log return', 'prev-year demand growth']:.2f}. "
             "Correlation does not show causation.")

# ---------------------------------------------------------------- 5. unusual price changes
fig, axes = new_fig(1, 2, figsize=(10, 3.8), gridspec_kw={"width_ratios": [2, 1]})
style_ax(axes[0]); style_ax(axes[1])
axes[0].plot(ret.index, ret.values * 100, color=BLUE, linewidth=1)
thr = 3 * ret.std()
out = ret[ret.abs() > thr]
axes[0].scatter(out.index, out.values * 100, color=RED, s=18, zorder=3)
axes[0].axhline(0, color=AXIS, linewidth=1)
axes[0].set_ylabel("monthly change (%)", color=INK2)
title(axes[0], "Monthly price change; red = beyond 3 standard deviations")
axes[1].hist(ret.values * 100, bins=40, color=BLUE, edgecolor=SURFACE)
title(axes[1], "Distribution")
axes[1].set_xlabel("monthly change (%)", color=INK2)
save_fig(fig, "eda5_price_changes.png")
top = ret.abs().sort_values(ascending=False).head(6)
notes.append("- **Unusual observations.** Largest monthly moves (log change): "
             + ", ".join(f"{d:%Y-%m} ({ret[d] * 100:+.1f}%)" for d in top.index)
             + f". Median absolute move is {ret.abs().median() * 100:.2f}%, so these are rare shocks (1995, 2008 and 2018 price "
             "spikes). No model that sees only past prices can anticipate them; expect large errors there. They are real events and are kept.")

# ---------------------------------------------------------------- 6. seasonality
# deseasonalise nothing; compare each month's average return with the overall average return of the SAME year
adj = ret - ret.groupby(ret.index.year).transform("mean")
by_m = adj.groupby(adj.index.month).agg(["mean", "std", "count"])
by_m["se"] = by_m["std"] / np.sqrt(by_m["count"])
fig, ax = new_fig(figsize=(8, 3.8))
style_ax(ax)
ax.bar(by_m.index, by_m["mean"] * 100, yerr=1.96 * by_m["se"] * 100, color=BLUE, edgecolor=SURFACE, capsize=2,
       error_kw=dict(ecolor=INK2, lw=1))
ax.axhline(0, color=AXIS, linewidth=1)
ax.set_xticks(range(1, 13))
ax.set_ylabel("avg. change vs. that year's average (%)", color=INK2, fontsize=8.5)
title(ax, "Seasonality: average monthly price change by calendar month (95% interval)")
save_fig(fig, "eda6_seasonality.png")
sig = by_m[(by_m["mean"] - 1.96 * by_m["se"] > 0) | (by_m["mean"] + 1.96 * by_m["se"] < 0)]
pos = sorted(sig.index[sig["mean"] > 0].tolist())
neg = sorted(sig.index[sig["mean"] < 0].tolist())
notes.append(f"- **Seasonality.** Measured as each month's average change relative to that year's average monthly change. "
             f"Months with a significantly above-average rise (95% interval excludes zero): {pos or 'none'}; "
             f"significantly below-average: {neg or 'none'}. The largest effect is {by_m['mean'].abs().max() * 100:.2f} percentage "
             "points, small next to the 1995/2008/2018 shocks, and testing 12 months at once will flag some by chance. "
             "Calendar-month features and a seasonal-naive baseline are still worth including.")

notes.append("\n**How this shapes the forecasting design:** (1) predict log price change instead of the level; (2) include recent "
             "returns and a 12-month price-vs-average gap; (3) include calendar-month features; (4) treat annual inflation and demand "
             "growth as weak, previous-year predictors; (5) evaluate against naive and seasonal-naive baselines.")
(REP / "eda_notes.md").write_text("\n".join(notes), encoding="utf-8")
print("\n".join(notes))
