c(f"- Geography: price file covers {price['geolocation'].nunique()} location ({price['geolocation'].iloc[0]}); "
  "demand and inflation are national. No geographic mismatch.")
c(f"- Rice classification: price file contains {price['commodity'].nunique()} classification "
  f"({price['commodity'].iloc[0]}). Demand is for rice as a whole. A per-classification model is not possible; "
  "the study is about regular-milled rice only.")
c("- Inflation is a percentage (annual average rate), not an index. Rice demand is a quantity (thousand MT), not a price.")
c("\n## Blockers and decisions\n")
c(f"1. **Frequency mismatch.** Price is monthly; demand and inflation are annual. Repeating an annual value across "
  "12 months would be misleading, and using the current year's annual figure would leak information that is only "
  "known after the year ends. **Recommended solution (implemented):** keep the model monthly and give each month the "
  "*previous* calendar year's annual inflation and demand growth. This is information that was actually available "
  "when the forecast was made, and it is documented as a low-resolution predictor.")
if usable_infl != [INFLATION_COL]:
    c(f"2. **Inflation column.** Usable column(s): {usable_infl}. Expected {INFLATION_COL}.")
else:
    bad = filler.loc[filler["verdict"] != "usable", "column"].tolist()
    c(f"2. **Inflation filler.** Columns {bad} repeat one value in most years and are NOT used. Only `{INFLATION_COL}` "
      "(World Bank) is usable. The proposal cites BSP/PSA inflation; that source would need to be re-downloaded.")
if flat_years:
    c(f"3. **Placeholder price year(s) {flat_years}.** All 12 monthly prices are identical. A naive forecast would be "
      "scored as nearly perfect on these months and any model would be trained on made-up variation. **Recommended "
      "solution (implemented):** treat these months as missing, so the usable price series ends before them "
      "(config `EXCLUDE_FLAT_PRICE_YEARS` in common.py).")
c(f"4. **Forecast origin.** Because the price file ends in {price['date'].max():%Y-%m}"
  + (f" and {', '.join(map(str, flat_years))} is excluded, the last trustworthy month is {pd.Timestamp(str(min(flat_years)) + '-01-01') - pd.DateOffset(months=1):%Y-%m}" if flat_years else "")
  + ". Genuine 'future' forecasts start from that month, which is in the past relative to today. They cannot be "
  "compared with real prices using the files provided.")
c("5. **Single series.** One national series means no cross-sectional data, so the effective sample size is the number "
  "of months, and consecutive months are strongly autocorrelated.")
c("\n## Join design\n")
c("- Key: `ref_year = calendar year of the price month - 1`, joined many-to-one (`validate='m:1'`) from the annual table "
  "to the monthly table. The script asserts that the number of monthly rows does not change after the join.")
c("- Corn rows in the demand file are dropped (not relevant); reported in the cleaning log.")
(REP / "data_compatibility_report.md").write_text("\n".join(C), encoding="utf-8")
