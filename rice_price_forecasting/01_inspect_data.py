def p(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    L.append(s)


def runs_of_identical(values: pd.Series, min_len=6):
    """Return (start_index, end_index, length, value) for runs of identical consecutive values."""
    out, start = [], 0
    v = values.to_numpy()
    for i in range(1, len(v) + 1):
        if i == len(v) or v[i] != v[start]:
            if i - start >= min_len:
                out.append((values.index[start], values.index[i - 1], i - start, v[start]))
            start = i
    return out


def generic_report(name, path, df, date_desc):
    p(f"\n## {name}\n")
    p(f"- File: `{path.name}` (CSV, {path.stat().st_size:,} bytes)")
    p(f"- Rows x columns: {df.shape[0]} x {df.shape[1]}")
    p("- Columns and dtypes:\n")
    p(md_table(pd.DataFrame({"column": df.columns, "dtype": [str(t) for t in df.dtypes],
                             "missing": df.isna().sum().values,
                             "n_unique": df.nunique().values})))
    p(f"\n- Exact duplicate rows: {int(df.duplicated().sum())}")
    p(f"- Date coverage: {date_desc}")
    obj_cols = [c for c in df.columns if df[c].dtype == object]
    numeric_like = []
    for c in obj_cols:
        conv = pd.to_numeric(df[c].astype(str).str.replace(r"[₱$,%\s]", "", regex=True), errors="coerce")
        if conv.notna().mean() > 0.9:
            numeric_like.append(c)
    p(f"- Text columns that look numeric (strings/currency symbols): {numeric_like or 'none'}")
    p("\nFirst rows:\n")
    p("```\n" + df.head(4).to_string(index=False) + "\n```")
    p("Last rows:\n")
    p("```\n" + df.tail(4).to_string(index=False) + "\n```")
    num = df.select_dtypes("number")
    if not num.empty:
        p("Summary statistics (numeric columns):\n")
        p("```\n" + num.describe().T.round(3).to_string() + "\n```")


p("# Dataset inspection report (auto-generated by 01_inspect_data.py)")

# ---------------------------------------------------------------- price
missing_files = [f.name for f in (PRICE_FILE, DEMAND_FILE, INFLATION_FILE) if not f.exists()]
if missing_files:
    raise SystemExit(f"Missing file(s): {missing_files}. Put them in {DATA}")

price = pd.read_csv(PRICE_FILE)
price["date"] = pd.to_datetime(price["date"], errors="coerce")
generic_report("1. Rice retail price", PRICE_FILE, price,
               f"{price['date'].min():%Y-%m-%d} to {price['date'].max():%Y-%m-%d}")
steps = price["date"].sort_values().diff().dropna().dt.days
p(f"- Observation frequency: monthly (gap between consecutive dates: min {steps.min()} d, max {steps.max()} d; "
  f"all on day 1 of month: {bool((price['date'].dt.day == 1).all())})")
full = pd.date_range(price["date"].min(), price["date"].max(), freq="MS")
p(f"- Months expected between first and last date: {len(full)}; present: {price['date'].nunique()}; "
  f"missing months: {len(full.difference(price['date']))}")
p(f"- Duplicate (geolocation, commodity, date) keys: {int(price.duplicated(['geolocation', 'commodity', 'date']).sum())}")
p(f"- Geographic categories: {sorted(price['geolocation'].unique())}")
p(f"- Rice classifications: {sorted(price['commodity'].unique())}")
p(f"- Invalid prices (<= 0 or NaN): {int((~(price['retail_price'] > 0)).sum())}")
ps = price.sort_values("date").set_index("date")["retail_price"]
chg = ps.pct_change().dropna()
big = chg[chg.abs() > 0.10]
p(f"- Month-over-month moves larger than 10%: {len(big)} -> "
  + ", ".join(f"{d:%Y-%m} ({v:+.1%})" for d, v in big.items()))
flat_months = runs_of_identical(ps, min_len=6)
p("- Runs of >= 6 identical consecutive prices: "
  + (", ".join(f"{a:%Y-%m} to {b:%Y-%m} ({n} months at {v})" for a, b, n, v in flat_months) or "none"))
ann = ps.groupby(ps.index.year)
flat_years = [int(y) for y, g in ann if len(g) == 12 and g.nunique() == 1]
p(f"- Years whose 12 monthly prices are all identical: {flat_years or 'none'}")

# ---------------------------------------------------------------- demand
demand = pd.read_csv(DEMAND_FILE)
generic_report("2. Rice demand (PSA supply utilization)", DEMAND_FILE, demand,
               f"years {demand['year'].min()} to {demand['year'].max()}")
p(f"- Observation frequency: annual (year gaps: {sorted(set(demand.sort_values('year').groupby('commodity')['year'].diff().dropna().astype(int)))})")
p(f"- Commodities: {demand['commodity'].value_counts().to_dict()}  (only 'Rice' is relevant here)")
rice_d = demand[demand["commodity"] == "Rice"]
p(f"- Rice rows: {len(rice_d)} years; duplicate years: {int(rice_d['year'].duplicated().sum())}")
p("- Units: PSA supply-utilization figures are in thousand metric tons; per-capita columns are kg/yr and g/day "
  "(stored as rounded integers).")
chk = (rice_d["su beginning stocks"] + rice_d["su production"] + rice_d["su imports"] - rice_d["su gross supply"]).abs().max()
p(f"- Arithmetic check beginning stocks + production + imports vs gross supply: max abs difference = {chk}")

# ---------------------------------------------------------------- inflation
