p(f"- Annual demand: {len(rice_d)} observations. Annual inflation: {len(infl)} observations. "
  "Too few distinct values to learn reliable year-level effects; treat them as weak, low-resolution predictors.")

(REP / "dataset_inspection_report.md").write_text("\n".join(L), encoding="utf-8")

